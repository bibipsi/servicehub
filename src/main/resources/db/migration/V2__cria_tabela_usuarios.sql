-- Usuários da plataforma. Cada usuário possui um único papel (RBAC).
-- A senha é armazenada somente como hash BCrypt (60 caracteres).
CREATE TABLE usuarios (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(100) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    senha_hash    VARCHAR(255) NOT NULL,
    papel         VARCHAR(20)  NOT NULL DEFAULT 'CLIENT',
    telefone      VARCHAR(20),
    ativo         BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em     TIMESTAMP(6) NOT NULL,
    atualizado_em TIMESTAMP(6) NOT NULL,

    CONSTRAINT uk_usuarios_email UNIQUE (email),
    CONSTRAINT chk_usuarios_email_minusculo CHECK (email = LOWER(email)),
    CONSTRAINT chk_usuarios_papel CHECK (papel IN ('ADMIN', 'PROVIDER', 'CLIENT'))
);
