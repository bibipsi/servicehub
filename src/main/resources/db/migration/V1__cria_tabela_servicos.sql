-- Estrutura da tabela de serviços da primeira etapa, equivalente à que o Hibernate
-- gerava com ddl-auto=update. Em bancos que já possuem essa tabela, o Flyway registra
-- esta versão como baseline (spring.flyway.baseline-on-migrate) e não a executa.
CREATE TABLE servicos (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome            VARCHAR(100)   NOT NULL,
    descricao       VARCHAR(500),
    preco           NUMERIC(10, 2) NOT NULL,
    duracao_minutos INTEGER        NOT NULL,
    categoria       VARCHAR(30)    NOT NULL,
    ativo           BOOLEAN        NOT NULL,
    criado_em       TIMESTAMP(6)   NOT NULL,
    atualizado_em   TIMESTAMP(6)   NOT NULL,

    CONSTRAINT uk_servicos_nome UNIQUE (nome),
    CONSTRAINT chk_servicos_categoria CHECK (categoria IN
        ('LIMPEZA', 'MANUTENCAO', 'TECNOLOGIA', 'CONSULTORIA', 'BELEZA', 'OUTROS'))
);
